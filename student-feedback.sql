-- HL Preparation: Student Feedback table and secure access policies
create table if not exists public.student_feedback (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  category text not null check (category in ('सुझाव','समस्या','प्रशंसा','नयाँ सुविधा','अन्य')),
  message text not null check (char_length(message) between 5 and 2000),
  status text not null default 'new' check (status in ('new','reviewed','resolved')),
  created_at timestamptz not null default now()
);
create index if not exists student_feedback_created_at_idx on public.student_feedback(created_at desc);
create index if not exists student_feedback_user_id_idx on public.student_feedback(user_id);
alter table public.student_feedback enable row level security;
drop policy if exists "students_submit_own_feedback" on public.student_feedback;
drop policy if exists "admins_read_all_feedback" on public.student_feedback;
drop policy if exists "admins_update_feedback_status" on public.student_feedback;
create policy "students_submit_own_feedback" on public.student_feedback
 for insert to authenticated with check (user_id = auth.uid());
create policy "admins_read_all_feedback" on public.student_feedback
 for select to authenticated using (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));
create policy "admins_update_feedback_status" on public.student_feedback
 for update to authenticated using (exists (select 1 from public.admin_users a where a.user_id = auth.uid()))
 with check (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));
grant insert on public.student_feedback to authenticated;
grant select, update on public.student_feedback to authenticated;
